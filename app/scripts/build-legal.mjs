// Bundles docs/legal/*.md into src/lib/legal.generated.ts so the app can show them offline.
// Run after editing the documents: node app/scripts/build-legal.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const read = (name) =>
  readFileSync(fileURLToPath(new URL(`../../docs/legal/${name}`, import.meta.url)), 'utf8')
    .replace(/\r\n?/g, '\n') // same output on Windows and Linux
    .replace(/<!--[\s\S]*?-->/g, '') // drafting notes are not for readers
    .trim();

const out = `// Generated by scripts/build-legal.mjs from docs/legal. Do not edit by hand.
export const LEGAL = {
  privacy: ${JSON.stringify(read('privacy-policy.md'))},
  terms: ${JSON.stringify(read('terms-of-service.md'))},
} as const;
`;
writeFileSync(fileURLToPath(new URL('../src/lib/legal.generated.ts', import.meta.url)), out);
console.log('legal.generated.ts written');
